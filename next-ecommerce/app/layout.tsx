import './globals.css'
import Nav from './component/Nav'
import {getServerSession} from 'next-auth/next'
import {options} from "../pages/api/auth/[...nextauth]"
import Hydrate from './component/Hydrate'
import {Roboto,Lobster_Two} from 'next/font/google'

//Define main font

const roboto=Roboto({weight:['400','500','700'],subsets:['latin'], variable:'--font-robot'})
const lobster= Lobster_Two({weight:'700', subsets:['latin'], variable:'--font-lobster'})

export const metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
}

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode
}) {
  //Fetch the user 

  const session= await getServerSession(options)
  

  return (
    <html  className={` ${roboto.variable} ${lobster.variable}`} lang="en">
     
        <Hydrate>
          <Nav user={session?.user} expires={session?.expires as string} />
          {children}
        </Hydrate>
      
    </html>
  )
}
